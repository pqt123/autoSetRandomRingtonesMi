const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const rootDir = path.resolve(__dirname, '..');
const configPath = path.join(rootDir, 'security', 'allowed-devices.json');
const keystorePropsPath = path.join(rootDir, 'android', 'keystore.properties');
const outHeaderPath = path.join(
  rootDir,
  'modules',
  'expo-ringtone',
  'android',
  'src',
  'main',
  'cpp',
  'security_whitelist_gen.h'
);

const APP_PACKAGE_NAME = 'com.autoringtone.mi';
// Khóa bí mật cố định dùng để băm HMAC-SHA256 danh sách thiết bị (được mã hóa XOR khi nhúng vào C++)
const STATIC_PEPPER_HEX = '8f41c7d2905be63419fa7208cd35b1e4629a08f7c31de548b2069a71ef4382c5';

function normalizeDeviceId(raw) {
  return String(raw || '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '');
}

function xorEncode(buffer, seed) {
  const arr = [];
  for (let i = 0; i < buffer.length; i++) {
    const mask = ((i * 0x5d) + (seed * 0x33) + 0xa7) & 0xff;
    arr.push(buffer[i] ^ mask);
  }
  return arr;
}

function formatByteArray(bytes) {
  return '{ ' + bytes.map(b => '0x' + b.toString(16).padStart(2, '0')).join(', ') + ' }';
}

function resolveKeytoolBin() {
  if (process.env.JAVA_HOME) {
    const candidate = path.join(
      process.env.JAVA_HOME,
      'bin',
      process.platform === 'win32' ? 'keytool.exe' : 'keytool'
    );
    if (fs.existsSync(candidate)) return candidate;
  }
  return 'keytool';
}

function getSigningCertSha256Buffer() {
  const keytoolBin = resolveKeytoolBin();

  if (fs.existsSync(keystorePropsPath)) {
    const props = {};
    const lines = fs.readFileSync(keystorePropsPath, 'utf8').split(/\r?\n/);
    for (const line of lines) {
      const idx = line.indexOf('=');
      if (idx > 0) {
        props[line.slice(0, idx).trim()] = line.slice(idx + 1).trim();
      }
    }
    const ksFile = path.resolve(rootDir, 'android', 'app', props.storeFile || '');
    if (fs.existsSync(ksFile) && props.keyAlias && props.storePassword) {
      const der = execFileSync(keytoolBin, [
        '-exportcert',
        '-keystore',
        ksFile,
        '-alias',
        props.keyAlias,
        '-storepass',
        props.storePassword,
      ]);
      return crypto.createHash('sha256').update(der).digest();
    }
  }

  // Fallback sang debug.keystore nếu chưa có keystore.properties
  const debugKs = path.join(rootDir, 'android', 'app', 'debug.keystore');
  const der = execFileSync(keytoolBin, [
    '-exportcert',
    '-keystore',
    debugKs,
    '-alias',
    'androiddebugkey',
    '-storepass',
    'android',
  ]);
  return crypto.createHash('sha256').update(der).digest();
}

function main() {
  if (!fs.existsSync(configPath)) {
    throw new Error(`Missing security config at: ${configPath}`);
  }

  const rawConfig = JSON.parse(fs.readFileSync(configPath, 'utf8'));
  const requireXiaomi = rawConfig.requireXiaomiBrand !== false ? 1 : 0;
  const rawIds = Array.isArray(rawConfig.allowedIds) ? rawConfig.allowedIds : [];

  const normalizedIds = Array.from(
    new Set(rawIds.map(normalizeDeviceId).filter(id => id.length >= 4))
  );

  if (normalizedIds.length === 0) {
    throw new Error('security/allowed-devices.json must contain at least 1 valid serial/deviceId in allowedIds.');
  }

  const pepperBuf = Buffer.from(STATIC_PEPPER_HEX, 'hex');
  const certSha256Buf = getSigningCertSha256Buffer();
  const pkgBuf = Buffer.from(APP_PACKAGE_NAME, 'utf8');

  const obfPepper = xorEncode(pepperBuf, 0x11);
  const obfCert = xorEncode(certSha256Buf, 0x22);
  const obfPkg = xorEncode(pkgBuf, 0x33);

  const obfDigests = normalizedIds.map((id, idx) => {
    const digest = crypto
      .createHmac('sha256', pepperBuf)
      .update('AUTORT_MI_V1:' + id, 'utf8')
      .digest();
    const rowSeed = (0x40 + (idx & 0x7f)) & 0xff;
    return {
      rowSeed,
      bytes: xorEncode(digest, rowSeed),
    };
  });

  const cppLines = [
    '// AUTO-GENERATED BY scripts/sync-security.js — DO NOT EDIT MANUALLY',
    '#pragma once',
    '#include <cstddef>',
    '#include <cstdint>',
    '',
    `static constexpr int kRequireXiaomiBrand = ${requireXiaomi};`,
    `static constexpr size_t kAllowedDeviceCount = ${obfDigests.length};`,
    `static constexpr size_t kObfPackageNameLen = ${obfPkg.length};`,
    '',
    `static const uint8_t kObfPepper[32] = ${formatByteArray(obfPepper)};`,
    `static const uint8_t kObfApkCertSha256[32] = ${formatByteArray(obfCert)};`,
    `static const uint8_t kObfPackageName[${obfPkg.length}] = ${formatByteArray(obfPkg)};`,
    '',
    'struct ObfAllowedEntry {',
    '  uint8_t seed;',
    '  uint8_t digest[32];',
    '};',
    '',
    `static const ObfAllowedEntry kObfAllowedEntries[${obfDigests.length}] = {`,
    ...obfDigests.map(d => `  { 0x${d.rowSeed.toString(16).padStart(2, '0')}, ${formatByteArray(d.bytes)} },`),
    '};',
    '',
  ];

  fs.mkdirSync(path.dirname(outHeaderPath), { recursive: true });
  fs.writeFileSync(outHeaderPath, cppLines.join('\n'), 'utf8');

  console.log(`🔐 [Security] Synced ${normalizedIds.length} authorized Xiaomi device(s) + APK Cert SHA-256 -> native C++ header.`);
}

main();

